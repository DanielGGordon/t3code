// Prints the Caddy config for the test-deploy pool. It ONLY prints to stdout;
// installing it is a privileged step (docs/test-deployments.md "Caddy
// bootstrap").
//
// Default: one site per slot on its own hostname, for the `caddy-t3-trusted`
// instance (/etc/caddy/t3-trusted.Caddyfile, :443, Let's Encrypt certs; the
// wildcard *.gordonlabs.dev DNS record already points at the box):
//
//   t3-test-7444.gordonlabs.dev -> 127.0.0.1:3774 ... t3-test-7453.gordonlabs.dev -> 127.0.0.1:3783
//
// wrapped in `# --- BEGIN t3-test-pool-hosts` / `# --- END t3-test-pool-hosts ---`
// markers, so it can be replaced in place. Hostnames follow
// T3_TEST_DEPLOY_URL_TEMPLATE (see testUrlFor).
//
// --legacy-ip: the original bare-IP sites `https://<HOST>:7444 ... :7453` for
// the main `caddy` instance (/etc/caddy/Caddyfile), on the pinned self-signed
// cert shared by the prod blocks. They still exist; new installs don't need them.

import { parseArgs } from "node:util";

import {
  assertNotProd,
  externalPorts,
  HOST,
  loopbackForExternal,
  testSiteAddressFor,
  unitForExternal,
} from "./test-deploy-lib.ts";

const HOSTS_BEGIN_MARKER = "# --- BEGIN t3-test-pool-hosts";
const HOSTS_END_MARKER = "# --- END t3-test-pool-hosts ---";

// The pinned self-signed pair the bare-IP sites in /etc/caddy/Caddyfile use.
const CERT = "/etc/caddy/dancode-server.crt";
const KEY = "/etc/caddy/dancode-server.key";

const PROXY = (loopbackPort: number, indent: string): string =>
  `${indent}reverse_proxy 127.0.0.1:${loopbackPort} {
${indent}    header_up Host {host}
${indent}    header_up X-Forwarded-Proto {scheme}
${indent}    header_up X-Real-IP {remote_host}
${indent}}`;

function hostBlockFor(externalPort: number, loopbackPort: number): string {
  return `${testSiteAddressFor(externalPort)} {
    encode gzip
${PROXY(loopbackPort, "    ")}
}`;
}

function legacyBlockFor(externalPort: number, loopbackPort: number): string {
  return `https://${HOST}:${externalPort} {
    tls ${CERT} ${KEY} {
        protocols tls1.2 tls1.3
    }
    encode gzip
    handle {
${PROXY(loopbackPort, "        ")}
    }
}`;
}

function slots(): Array<[number, number]> {
  return externalPorts().map((externalPort) => {
    const loopbackPort = loopbackForExternal(externalPort);
    // Never emit a block for a prod target.
    assertNotProd(externalPort, loopbackPort, unitForExternal(externalPort));
    return [externalPort, loopbackPort];
  });
}

function renderHostBlocks(): string {
  return [
    `${HOSTS_BEGIN_MARKER} (T3 Code test-deploy pool on hostnames; printed by t3code`,
    "#     scripts/test-deploy-caddy.ts, see its docs/test-deployments.md). t3-test-<port>.gordonlabs.dev",
    "#     -> 127.0.0.1:<port - 3670>. An idle slot answers 502. Leave these markers intact.",
    ...slots().map(([externalPort, loopbackPort]) => hostBlockFor(externalPort, loopbackPort)),
    HOSTS_END_MARKER,
  ].join("\n");
}

function renderLegacyBlocks(): string {
  return [
    "# --- T3 Code local test-deploy pool (slots 0..9) ---",
    "# Generated by scripts/test-deploy-caddy.ts --legacy-ip. Additive only.",
    ...slots().map(([externalPort, loopbackPort]) => legacyBlockFor(externalPort, loopbackPort)),
  ].join("\n\n");
}

function main(): void {
  const { values } = parseArgs({ options: { "legacy-ip": { type: "boolean", default: false } } });
  process.stdout.write(`${values["legacy-ip"] ? renderLegacyBlocks() : renderHostBlocks()}\n`);
}

main();
